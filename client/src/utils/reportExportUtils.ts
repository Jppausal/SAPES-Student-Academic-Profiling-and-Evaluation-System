import * as XLSX from 'xlsx';
import { jsPDF } from 'jspdf';
import { InstitutionalStudentSummary } from '../lib/api';
import { formatAcademicGwa } from './mongoAcademicGwa';
import { formatStatusLabel } from './formatStatusLabel';

export interface ExportOptions {
  filterQuery?: string;
  activeTerm?: string;
  generatedBy?: string;
  callerRole?: string;
  stats?: { ip: number; pwd: number; probation: number; evaluated: number; enrolled?: number };
  appliedFilters?: {
    academicYear?: string;
    semester?: string;
    department?: string;
    yearLevel?: string;
    enrollmentStatus?: string;
    dateRange?: string;
  };
  aggregations?: {
    byProgram?: Array<{ program: string; departmentCode?: string; total: number; enrolled: number }>;
    byYearLevel?: Array<{ yearLevel: number | string; label: string; total: number; enrolled: number }>;
    byAcademicPeriod?: Array<{ academicYear: string; semester: string; studentCount: number; recordCount: number }>;
  };
}

export function verifyExportAuthorization(options: ExportOptions = {}) {
  if (options.callerRole && options.callerRole !== 'admin') {
    throw new Error('Export functions are strictly restricted to authorized administrative personnel.');
  }
}

export function getFormattedStudentRow(student: InstitutionalStudentSummary) {
  const name = [
    student.personalInformation?.lastName,
    student.personalInformation?.firstName,
    student.personalInformation?.middleName,
  ].filter(Boolean).join(', ');

  const classifications = [
    student.classification?.studentType,
    student.classification?.isIP ? 'IP' : '',
    student.classification?.isPWD ? 'PWD' : '',
    student.classification?.isShifter ? 'Shifter' : '',
    student.classification?.isTransferee ? 'Transferee' : '',
  ].filter(Boolean).join('; ');

  const program = student.program || student.classification?.program || student.enrollmentInformation?.course || 'General Curriculum';
  const department = student.department || student.enrollmentInformation?.department || 'COT';
  const yearLevel = student.yearLevel ? (typeof student.yearLevel === 'number' ? `Year ${student.yearLevel}` : String(student.yearLevel)) : 'Year 1';
  const section = student.section || 'A';
  const enrollmentStatus = formatStatusLabel(student.enrollmentStatus || 'Enrolled');

  const academicStatus = formatStatusLabel(student.academicStatus?.currentStatus || 'Regular');
  const onProbation = student.academicStatus?.isOnProbation ? 'YES' : 'NO';
  const rawEval = student.facultyEvaluation?.evaluationStatus;
  const evalStatus = formatStatusLabel(rawEval || 'Pending');
  const reasons = (student.facultyEvaluation?.reasons || []).join('; ');
  const remarks = student.facultyEvaluation?.remarks || '';
  const evaluator = student.facultyEvaluation?.faculty?.username || 'N/A';

  const latestTerm = student.latestAcademicPeriod
    ? `${student.latestAcademicPeriod.academicYear} ${student.latestAcademicPeriod.semester}`
    : 'N/A';
  const latestOverallGwa = student.latestAcademicPeriod ? formatAcademicGwa(student.latestAcademicPeriod.overallGwa) : 'N/A';
  const latestMajorGwa = student.latestAcademicPeriod ? formatAcademicGwa(student.latestAcademicPeriod.majorSubjectGwa) : 'N/A';
  const cumOverallGwa = formatAcademicGwa(student.overallGwa);
  const cumMajorGwa = formatAcademicGwa(student.majorSubjectGwa);

  return {
    id: student.institutionId,
    name: name || 'Name not recorded',
    program,
    department,
    yearLevel,
    section,
    enrollmentStatus,
    classifications: classifications || 'Regular',
    religion: student.religiousInformation?.religion || 'Not recorded',
    academicStatus,
    onProbation,
    termsCount: student.academicRecordCount || 0,
    subjectsCount: student.subjectCount || 0,
    latestTerm,
    latestOverallGwa,
    latestMajorGwa,
    cumOverallGwa,
    cumMajorGwa,
    evalStatus,
    reasons,
    remarks,
    evaluator,
  };
}

export function exportStudentsToCSV(students: InstitutionalStudentSummary[], options: ExportOptions = {}) {
  verifyExportAuthorization(options);
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const dateStr = new Date().toLocaleString('en-PH', { dateStyle: 'long', timeStyle: 'short' });
  const filterDesc = options.filterQuery ? `Filtered by "${options.filterQuery}"` : 'All Enrolled / Matching Records';

  const filterMeta: string[] = [
    `Generated: ${dateStr}`,
    `Generated by: ${options.generatedBy || 'System Administrator'}`,
    `Total Records: ${students.length}`,
    `Filter Scope: ${filterDesc}`
  ];

  if (options.appliedFilters) {
    const f = options.appliedFilters;
    if (f.department) filterMeta.push(`Department: ${f.department}`);
    if (f.academicYear) filterMeta.push(`Academic Year: ${f.academicYear}`);
    if (f.semester) filterMeta.push(`Semester: ${f.semester}`);
    if (f.yearLevel) filterMeta.push(`Year Level: ${f.yearLevel}`);
    if (f.enrollmentStatus) filterMeta.push(`Enrollment Status: ${f.enrollmentStatus}`);
    if (f.dateRange) filterMeta.push(`Date Range: ${f.dateRange}`);
  }

  const rows: string[][] = [
    ['BUKIDNON STATE UNIVERSITY'],
    ['COLLEGE OF TECHNOLOGIES — STUDENT ACADEMIC PROFILING & EVALUATION SYSTEM (SAPES)'],
    ['OFFICIAL INSTITUTIONAL ENROLLMENT & ACADEMIC EVALUATION REPORT'],
    filterMeta,
    [], // Blank separator
    [
      'Student ID',
      'Student Name',
      'Program / Course',
      'Department',
      'Year Level',
      'Section',
      'Enrollment Status',
      'Classification',
      'Religion',
      'Academic Status',
      'On Probation',
      'Terms Recorded',
      'Subjects Recorded',
      'Latest Term',
      'Latest Overall GWA',
      'Latest Major GWA',
      'Cumulative Overall GWA',
      'Cumulative Major GWA',
      'Evaluation Status',
      'Evaluation Reasons',
      'Evaluation Remarks',
      'Evaluator',
    ],
  ];

  for (const s of students) {
    const d = getFormattedStudentRow(s);
    rows.push([
      d.id,
      d.name,
      d.program,
      d.department,
      d.yearLevel,
      d.section,
      d.enrollmentStatus,
      d.classifications,
      d.religion,
      d.academicStatus,
      d.onProbation,
      String(d.termsCount),
      String(d.subjectsCount),
      d.latestTerm,
      d.latestOverallGwa,
      d.latestMajorGwa,
      d.cumOverallGwa,
      d.cumMajorGwa,
      d.evalStatus,
      d.reasons,
      d.remarks,
      d.evaluator,
    ]);
  }

  // Format into CSV escaping quotes and commas
  const csvContent = rows
    .map((row) =>
      row
        .map((cell) => {
          const str = String(cell ?? '');
          return `"${str.replace(/"/g, '""')}"`;
        })
        .join(',')
    )
    .join('\r\n');

  // Add UTF-8 BOM so Excel opens with correct encoding
  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `SAPES_Enrollment_Report_${timestamp}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

