/**
 * Direct vector PDF export using jsPDF (A116)
 */
export function exportStudentsToPDF(students: InstitutionalStudentSummary[], options: ExportOptions = {}) {
  verifyExportAuthorization(options);
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const dateStr = new Date().toLocaleString('en-PH', { dateStyle: 'long', timeStyle: 'short' });
  const filterDesc = options.filterQuery ? `Filtered by "${options.filterQuery}"` : 'All Enrolled / Matching Records';
  const generatedBy = options.generatedBy || 'System Administrator';

  // Landscape A4: 842 x 595 points
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 36; // 0.5 inch margins

  let cursorY = margin;

  const renderHeader = (isFirstPage: boolean) => {
    // Header banner
    doc.setFillColor(15, 23, 42); // slate-900
    doc.rect(margin, cursorY, pageWidth - margin * 2, 28, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text('BUKIDNON STATE UNIVERSITY — COLLEGE OF TECHNOLOGIES', margin + 12, cursorY + 18);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('SAPES ENROLLMENT & ACADEMIC EVALUATION REPORT', pageWidth - margin - 12, cursorY + 18, { align: 'right' });

    cursorY += 36;

    if (isFirstPage) {
      doc.setTextColor(15, 23, 42);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(13);
      doc.text('OFFICIAL ENROLLED STUDENTS MASTERLIST & EVALUATION REPORT', margin, cursorY);
      cursorY += 16;

      // Meta box
      doc.setDrawColor(203, 213, 225); // slate-300
      doc.setFillColor(248, 250, 252); // slate-50
      doc.roundedRect(margin, cursorY, pageWidth - margin * 2, 38, 4, 4, 'FD');

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(51, 65, 85);

      const col1X = margin + 12;
      const col2X = margin + 260;
      const col3X = margin + 520;

      doc.text(`Generated: ${dateStr}`, col1X, cursorY + 14);
      doc.text(`Prepared By: ${generatedBy}`, col1X, cursorY + 27);

      const f = options.appliedFilters;
      const filterSummary = [
        f?.department ? `Dept: ${f.department}` : '',
        f?.academicYear ? `AY: ${f.academicYear}` : '',
        f?.semester ? `Sem: ${f.semester}` : '',
        f?.yearLevel ? `Year: ${f.yearLevel}` : '',
        f?.enrollmentStatus ? `Status: ${f.enrollmentStatus}` : '',
      ].filter(Boolean).join(' | ') || 'All Programs & Periods';

      doc.text(`Active Filters: ${filterSummary}`, col2X, cursorY + 14);
      doc.text(`Search Criteria: ${filterDesc}`, col2X, cursorY + 27);

      doc.text(`Total Records Listed: ${students.length}`, col3X, cursorY + 14);
      if (options.stats) {
        doc.text(
          `Enrolled: ${options.stats.enrolled ?? students.length} | IP: ${options.stats.ip} | PWD: ${options.stats.pwd} | Probation: ${options.stats.probation}`,
          col3X,
          cursorY + 27
        );
      }

      cursorY += 46;
    }
  };

  renderHeader(true);

  // Table Columns Setup
  const headers = [
    { title: 'Student ID', width: 75 },
    { title: 'Student Name', width: 130 },
    { title: 'Program / Course', width: 155 },
    { title: 'Year / Sec', width: 55 },
    { title: 'Enroll Status', width: 65 },
    { title: 'Academic Standing', width: 85 },
    { title: 'Period GWA', width: 55 },
    { title: 'Cum GWA', width: 55 },
    { title: 'Faculty Evaluation', width: 95 },
  ];

  const renderTableHead = () => {
    doc.setFillColor(30, 41, 59); // slate-800
    doc.rect(margin, cursorY, pageWidth - margin * 2, 18, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);

    let curX = margin + 6;
    for (const h of headers) {
      doc.text(h.title, curX, cursorY + 12);
      curX += h.width;
    }
    cursorY += 20;
  };

  renderTableHead();

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);

  const rowHeight = 16;

  for (let i = 0; i < students.length; i++) {
    // Check if new page is needed
    if (cursorY + rowHeight > pageHeight - 55) {
      doc.addPage();
      cursorY = margin;
      renderHeader(false);
      renderTableHead();
    }

    const s = students[i];
    const d = getFormattedStudentRow(s);

    const isEven = i % 2 === 0;
    if (!isEven) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, cursorY - 3, pageWidth - margin * 2, rowHeight, 'F');
    }

    doc.setDrawColor(226, 232, 240);
    doc.line(margin, cursorY + rowHeight - 3, pageWidth - margin, cursorY + rowHeight - 3);

    doc.setTextColor(15, 23, 42);

    let curX = margin + 6;

    // ID
    doc.setFont('courier', 'normal');
    doc.text(d.id, curX, cursorY + 8);
    curX += headers[0].width;

    // Name
    doc.setFont('helvetica', 'bold');
    const nameTrunc = d.name.length > 25 ? d.name.slice(0, 23) + '...' : d.name;
    doc.text(nameTrunc, curX, cursorY + 8);
    curX += headers[1].width;

    // Program
    doc.setFont('helvetica', 'normal');
    const progTrunc = d.program.length > 30 ? d.program.slice(0, 28) + '...' : d.program;
    doc.text(progTrunc, curX, cursorY + 8);
    curX += headers[2].width;

    // Year / Sec
    doc.text(`${d.yearLevel} ${d.section}`, curX, cursorY + 8);
    curX += headers[3].width;

    // Enrollment Status
    doc.text(d.enrollmentStatus, curX, cursorY + 8);
    curX += headers[4].width;

    // Academic Status
    if (d.onProbation === 'YES') {
      doc.setTextColor(185, 28, 28);
      doc.setFont('helvetica', 'bold');
      doc.text(`${d.academicStatus} (Probation)`, curX, cursorY + 8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(15, 23, 42);
    } else {
      doc.text(d.academicStatus, curX, cursorY + 8);
    }
    curX += headers[5].width;

    // Period GWA
    doc.text(d.latestOverallGwa, curX, cursorY + 8);
    curX += headers[6].width;

    // Cum GWA
    doc.text(d.cumOverallGwa, curX, cursorY + 8);
    curX += headers[7].width;

    // Evaluation
    const evalText = d.evalStatus === 'Eligible' ? 'Eligible' : d.evalStatus === 'Not Eligible' ? 'Not Eligible' : 'Pending';
    if (evalText === 'Eligible') {
      doc.setTextColor(21, 128, 61);
    } else if (evalText === 'Not Eligible') {
      doc.setTextColor(185, 28, 28);
    } else {
      doc.setTextColor(180, 83, 9);
    }
    doc.text(evalText, curX, cursorY + 8);
    doc.setTextColor(15, 23, 42);

    cursorY += rowHeight;
  }

  // Footer & Page numbers on all pages
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `BukSU College of Technologies — SAPES Official Report | Page ${p} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 16,
      { align: 'center' }
    );
  }

  doc.save(`SAPES_Enrollment_Report_${timestamp}.pdf`);
}

